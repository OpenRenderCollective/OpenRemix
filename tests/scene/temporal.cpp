#include "scene/temporal.h"
#include "scene/fixtures.h"
using namespace remix::scene;
using remix::test::require;
int main() {
  TemporalHistory history;
  Draw a;
  a.instanceId = 17;
  a.mesh = std::make_shared<Mesh>();
  a.surface = std::make_shared<Surface>();
  a.material = std::make_shared<Material>();
  a.material->texture = std::make_shared<Texture>();
  a.material->texture->pixels = {1, 1, true, {{255, 255, 255, 255}}};
  a.model = identity();
  history.begin({1, 1}, 7, 1920, 1080);
  require(history.reset(), "First frame needs clear");
  history.stage(a);
  require(!history.previous(a), "Unsubmitted frame became history");
  history.begin({1, 1}, 7, 1920, 1080);
  require(history.reset(), "Discarded submission advanced epochs");
  history.stage(a);
  history.commit();
  a.model[12] = 10;
  history.begin({1, 1}, 7, 1920, 1080);
  require(!history.reset(), "Rigid motion reset history");
  require(history.previous(a) && history.previous(a)->draw.model[12] == 0, "Previous submitted transform was lost");
  history.stage(a);
  auto unsubmitted = a;
  unsubmitted.model[12] = 20;
  history.stage(unsubmitted);
  history.begin({1, 1}, 7, 1920, 1080);
  require(history.previous(a)->draw.model[12] == 0, "Discarded transform was retained");
  auto b = a;
  b.instanceId = 18;
  history.stage(b);
  history.stage(a, 3);
  history.commit();
  history.begin({1, 1}, 7, 1920, 1080);
  require(history.previous(a) && history.previous(b), "Reordered stable identities lost history");
  require(history.previous(a)->textureFrame == 3, "Previous rendered atlas frame was lost");
  require(!history.reset(), "Atlas animation reset global history");
  a.bones = std::make_shared<std::vector<Matrix>>(1, identity());
  (*a.bones)[0][12] = .2f;
  require(history.previous(a), "Compatible deformation invalidated geometry correspondence");
  auto replaced = a;
  replaced.mesh = std::make_shared<Mesh>();
  require(!history.previous(replaced), "Replacement reused incompatible geometry");
  require(!history.previousGeometry(replaced), "Replacement retained motion correspondence");
  auto changed = a;
  changed.material = std::make_shared<Material>(*a.material);
  changed.material->tint[0] = 0;
  require(!history.previous(changed) && !history.reset(), "Material edit was not rejected locally");
  require(history.previousGeometry(changed), "Tint change discarded geometric motion history");
  changed.material = std::make_shared<Material>(*a.material);
  changed.material->texture = std::make_shared<Texture>(*a.material->texture);
  changed.material->texture->contentHash = 0;
  changed.material->texture->pixels.mips[0][3] = 0;
  require(!history.previous(changed) && !history.reset(), "Animated texture alpha retained stale history");
  require(history.previousGeometry(changed), "Texture animation discarded geometric motion history");
  changed.material->texture->pixels = {2, 1, true, {{255, 255, 255, 255, 0, 0, 0, 255}}};
  changed.material->texture->contentHash = 0;
  history.stage(changed, 4);
  history.commit();
  history.begin({1, 1}, 7, 1920, 1080);
  auto animated = changed;
  animated.material = std::make_shared<Material>(*changed.material);
  animated.material->texture = std::make_shared<Texture>(*changed.material->texture);
  animated.material->texture->pixels.mips[0][4] = 255;
  animated.material->texture->contentHash = 0;
  require(!history.previous(animated), "Changed atlas retained identical-shading history");
  require(history.previousGeometry(animated) && history.previousGeometry(animated)->textureFrame == 4,
          "An unrelated atlas tile discarded stable geometry history");
  auto local = a;
  local.instanceId = 0;
  require(!history.previous(local), "Frame-local instance gained history");
  require(!history.previousGeometry(local), "Frame-local instance gained geometric history");
  history.stage(a);
  history.commit();
  history.begin({1, 1}, 7, 1920, 1080);
  require(!history.previous(b), "Newly visible object retained old correspondence");
  history.begin({2, 1}, 7, 1920, 1080);
  require(history.reset(), "World change did not clear");
  history.stage(a);
  history.commit();
  history.begin({2, 2}, 7, 1920, 1080);
  require(history.reset(), "Camera cut/rebase did not clear");
  history.stage(a);
  history.commit();
  history.begin({2, 2}, 8, 1920, 1080);
  require(history.reset(), "Integrator change did not clear");
  history.stage(a);
  history.commit();
  history.begin({2, 2}, 8, 1280, 720);
  require(history.reset(), "Resize did not clear");
  require(history.frames() == 7, "Only submitted frames should count");
}
