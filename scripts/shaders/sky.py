"""NUMOS sky shaders: the NUMOS passes and OpenRemix's adapter passes, compiled with the pinned slangc.

NUMOS's committed pass table (src/generated/passes.inc) was generated with an RTX Remix build of
slangc that has no public release. The pinned public slangc produces different SPIR-V bytes, so
the check here is that every pass reflects exactly the table's workgroup size, push-constant size
and bindings, and that the shared C++/Slang structs keep the layout the core library asserts.

The night sky's stars and diffuse galaxy are NUMOS's procedural ones (tools/build_custom_sky.py,
which needs numpy), not the catalogue files in assets/nightsky, whose Milky Way data is CC BY-SA.
The moon's surface is assets/nightsky/moon.bin (NASA media, not copyrighted).
"""
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

import generate

NUMOS = generate.ROOT / 'third_party/numos/numos-sky'
ADAPTERS = generate.ROOT / 'src/native/sky/shaders'
PASS_TABLE = NUMOS / 'src/generated/passes.inc'
LAYOUT_CHECKS = NUMOS / 'include/numos/detail/layout_checks.h'
HASH = re.compile(r'0x[0-9a-f]{16}ull')
# numos::NightSkyAssets members in embedded order; the seed fixes the generated galaxy.
NIGHT_SKY = ('stars', 'milkyWay', 'starlightLow', 'moon')
NIGHT_SKY_SEED = '1'


def tools():
    # Bytecode would land in the submodule.
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(NUMOS / 'tools'))
    import build_shaders
    import gen_layout_checks
    import gen_pass_table
    return build_shaders, gen_pass_table, gen_layout_checks


def slangc():
    path = os.environ.get('REMIX_SLANGC')
    if not path:
        raise SystemExit('sky: no slangc recorded (toolchain.py --slang)')
    return path


def compile_numos(build_shaders, directory):
    subprocess.run([sys.executable, '-I', str(NUMOS / 'tools/build_shaders.py'), '--slangc', slangc(), '--out',
                    str(directory), '--jobs', str(os.cpu_count() or 4)], check=True, stdout=subprocess.DEVNULL)


def check_layout(gen_pass_table, gen_layout_checks, directory):
    committed = HASH.sub('HASH', PASS_TABLE.read_text(encoding='utf-8').replace('\r\n', '\n'))
    if HASH.sub('HASH', gen_pass_table.generate(directory)) != committed:
        raise SystemExit('sky: NUMOS SPIR-V does not reflect the committed pass table; check the pinned slangc')
    if gen_layout_checks.generate(directory) != LAYOUT_CHECKS.read_text(encoding='utf-8').replace('\r\n', '\n'):
        raise SystemExit('sky: NUMOS shared struct layout differs from include/numos/detail/layout_checks.h')


def compile_adapters(build_shaders, directory):
    """[(stage name, SPIR-V path)] of every variant of src/native/sky/shaders/*.comp.slang."""
    stages = []
    for source in sorted(ADAPTERS.glob('*.comp.slang')):
        for name, defines in build_shaders.variants(source):
            output = directory / (name + '.spv')
            subprocess.run([slangc(), str(source), '-I', str(NUMOS / 'shaders'), '-I', str(ADAPTERS),
                            *build_shaders.FLAGS, *('-D' + d for d in defines), '-o', str(output)], check=True)
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.2', '--scalar-block-layout', str(output)],
                           check=True)
            stages.append((name.removesuffix('.comp').replace('.', '_'), output))
    # In file order, as the binding table lists them.
    return sorted(stages, key=lambda stage: stage[1].name)


def night_sky(directory):
    """{asset: bytes} of the night sky; without numpy the sky has the moon and no stars."""
    assets = {'moon': (NUMOS / 'assets/nightsky/moon.bin').read_bytes()}
    try:
        import numpy  # noqa: F401
    except ImportError:
        print('sky: numpy is not installed; the night sky is built without stars', file=sys.stderr)
        return assets
    subprocess.run([sys.executable, str(NUMOS / 'tools/build_custom_sky.py'), '--out', str(directory), '--seed',
                    NIGHT_SKY_SEED], check=True, stdout=subprocess.DEVNULL)
    files = {'stars': 'stars.bin', 'milkyWay': 'milkyway.bin', 'starlightLow': 'starlight_low.bin'}
    return assets | {asset: (directory / name).read_bytes() for asset, name in files.items()}


def write(numos_dir, adapters, adapter_table, night_sky_assets):
    rows = re.findall(r'^NUMOS_PASS\((\w+), "([^"]+)"', PASS_TABLE.read_text(encoding='utf-8'), re.M)
    shaders = [(name, numos_dir / spirv) for name, spirv in rows] + adapters
    header = ('// Generated by scripts/shaders/generate.py sky; do not edit.\n'
              '// NUMOS passes in numos::PassId order, then the adapter stages; each an XZ stream in embedded.bin.\n'
              '#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace remix::sky {\n'
              f'inline constexpr uint32_t numosPassCount = {len(rows)};\n'
              'enum class Stage : uint32_t {\n')
    header += ''.join(f'  {name},\n' for name, _ in adapters) + '  Count\n};\n'
    header += ('struct EmbeddedShader {\n  size_t offset, compressedBytes, bytes;\n};\n'
               '// Index: a numos::PassId, or numosPassCount + Stage.\n'
               'inline constexpr EmbeddedShader embeddedShaders[] = {\n')
    blob = bytearray()
    for name, path in shaders:
        data = path.read_bytes()
        packed = generate.compress(data)
        header += f'  {{{len(blob)}u, {len(packed)}u, {len(data)}u}}, // {name}\n'
        blob += packed
    header += '};\ninline constexpr const char *shaderNames[] = {\n'
    header += ''.join(f'  "{name}",\n' for name, _ in shaders) + '};\n'
    header += ('// The night sky\'s data in numos::NightSkyAssets order (stars, milkyWay, starlightLow, moon);\n'
               '// zero bytes where it was not built.\ninline constexpr EmbeddedShader embeddedNightSky[] = {\n')
    for asset in NIGHT_SKY:
        data = night_sky_assets.get(asset, b'')
        packed = generate.compress(data) if data else b''
        header += f'  {{{len(blob)}u, {len(packed)}u, {len(data)}u}}, // {asset}\n'
        blob += packed
    header += '};\n'
    header += '// embedded.bin (embedded_data.cpp).\nextern const unsigned char embeddedData[];\nextern const size_t embeddedDataBytes;\n}\n'
    target = generate.OUTPUT / 'sky/shaders/embedded.h'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(header)
    target.with_suffix('.bin').write_bytes(bytes(blob))
    target.with_name('embedded_data.cpp').write_text(generate.embedded_data('generate.py sky', 'sky'))
    # The adapters' binding table, in NUMOS's format (numos::PassInfo per Stage).
    target.with_name('adapter_passes.inc').write_text(adapter_table)


def process():
    build_shaders, gen_pass_table, gen_layout_checks = tools()
    with tempfile.TemporaryDirectory() as temporary:
        numos_dir, adapter_dir = Path(temporary) / 'numos', Path(temporary) / 'adapters'
        adapter_dir.mkdir()
        compile_numos(build_shaders, numos_dir)
        check_layout(gen_pass_table, gen_layout_checks, numos_dir)
        adapters = compile_adapters(build_shaders, adapter_dir)
        write(numos_dir, adapters, gen_pass_table.generate(adapter_dir), night_sky(Path(temporary) / 'night_sky'))
    # The adapter folder itself: adding an adapter changes its time stamp.
    generate.depend(PASS_TABLE, LAYOUT_CHECKS, ADAPTERS, NUMOS / 'assets/nightsky/moon.bin',
                    *(NUMOS / 'tools').glob('*.py'),
                    *(path for path in (NUMOS / 'shaders').rglob('*') if path.is_file()),
                    *(path for path in ADAPTERS.rglob('*') if path.is_file() and path.name != 'meson.build'))
