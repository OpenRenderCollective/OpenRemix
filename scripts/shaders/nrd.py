"""Pinned DXC diffuse SH, PBR SH, radiance and SIGMA permutations."""
from pathlib import Path
import json, os, re, struct, subprocess, tempfile
from storage_writes import widen
ROOT = Path(__file__).resolve().parents[2]
# DirectXShaderCompiler v1.9.2602.24 (May 2026 patch release).
DXC_TOOLCHAIN = json.loads(Path(__file__).with_name('toolchain.lock.json').read_text())['dxc']
DXC_VERSION = DXC_TOOLCHAIN['version']


def matches_dxc_version(output):
    """The pinned Linux and Windows binaries print different version formats."""
    if re.search(r'(?<![\d.])' + re.escape(DXC_VERSION) + r'(?![\d.])', output):
        return True
    major, minor, patch, build = DXC_VERSION.split('.')
    release = re.escape(DXC_TOOLCHAIN['release'].removeprefix('v'))
    return patch == '0' and re.search(
        rf'\bdxcompiler\.dll:\s+{major}\.{minor}\({build}-[0-9a-f]+\)\({release}\)', output) is not None


COMMON = '|NRD_SIGNAL=NRD_SIGNAL_DIFF|NRD_MODE=NRD_MODE_SH'
IDENTIFIERS = ['REBLUR_ClassifyTiles.cs.hlsl'] + [
    'REBLUR_' + name + '.cs.hlsl' + COMMON for name in
    ('PrePass', 'TemporalAccumulation', 'HistoryFix', 'Blur')] + [
    'REBLUR_PostBlur.cs.hlsl' + COMMON + '|TEMPORAL_STABILIZATION=' + str(x) for x in (0, 1)] + [
    'REBLUR_' + name + '.cs.hlsl' + COMMON for name in ('TemporalStabilization', 'SplitScreen')] + [
    'REBLUR_Validation.cs.hlsl', 'Clear.cs.hlsl|FLOAT=0', 'Clear.cs.hlsl|FLOAT=1']

IDENTIFIERS += [
    'SIGMA_ClassifyTiles.cs.hlsl|TRANSLUCENCY=1',
    'SIGMA_SmoothTiles.cs.hlsl', 'SIGMA_Copy.cs.hlsl',
    'SIGMA_Blur.cs.hlsl|TRANSLUCENCY=1|FIRST_PASS=1',
    'SIGMA_Blur.cs.hlsl|TRANSLUCENCY=1|FIRST_PASS=0',
    'SIGMA_TemporalStabilization.cs.hlsl|TRANSLUCENCY=1',
    'SIGMA_SplitScreen.cs.hlsl|TRANSLUCENCY=1']

IDENTIFIERS += [s.replace("NRD_MODE_SH", "NRD_MODE_RADIANCE") for s in IDENTIFIERS if "NRD_MODE_SH" in s]
IDENTIFIERS += ['REBLUR_HitDistReconstruction.cs.hlsl|NRD_SIGNAL=NRD_SIGNAL_DIFF|NRD_MODE=NRD_MODE_RADIANCE|MODE_5X5=0']
IDENTIFIERS += [s.replace('NRD_SIGNAL_DIFF|', 'NRD_SIGNAL_BOTH|')
                for s in IDENTIFIERS if 'NRD_SIGNAL_DIFF|' in s and 'NRD_MODE_RADIANCE' in s]
# REBLUR_DIFFUSE_SPECULAR_SH (PBR indirect); its hit distance reconstruction is the radiance one above.
IDENTIFIERS += [s.replace('NRD_SIGNAL_DIFF|', 'NRD_SIGNAL_BOTH|')
                for s in IDENTIFIERS if 'NRD_SIGNAL_DIFF|' in s and 'NRD_MODE_SH' in s]

def process(check=False, validate=False):
    target = ROOT / 'src/native/denoise/shaders/nrd_embedded.h'
    directory = ROOT / 'third_party/nrd'
    dxc = os.environ.get('REMIX_DXC', 'dxc')
    if not validate:
        version = subprocess.check_output([dxc, '--version'], text=True)
        if not matches_dxc_version(version):
            raise SystemExit(f'NRD shaders require pinned DXC {DXC_VERSION}; set REMIX_DXC')
    output = '// Generated by scripts/shaders/generate.py nrd; do not edit.\n#pragma once\n#include <cstdint>\n#include <cstddef>\nnamespace remix::denoise {\n'
    with tempfile.TemporaryDirectory() as tmp:
        for i, identifier in enumerate(IDENTIFIERS):
            binary = Path(tmp) / 'shader.spv'
            if validate:
                match = re.search(r'shader' + str(i) + r'\[\] = \{(.*?)\};', target.read_text(), re.S)
                words = [int(w, 16) for w in re.findall(r'0x[0-9a-f]+', match[1])]
                binary.write_bytes(struct.pack('<' + 'I' * len(words), *words))
            else:
                source, *defines = identifier.split('|')
                args = [dxc, '-spirv', '-fspv-target-env=vulkan1.2', '-T', 'cs_6_0', '-E', 'main', '-O3',
                        '-WX', '-all_resources_bound', '-DNRD_INTERNAL', '-I', str(directory/'External/MathLib'),
                        '-fvk-s-shift', '0', 'all', '-fvk-b-shift', '2', 'all',
                        '-fvk-u-shift', '3', 'all', '-fvk-t-shift', '20', 'all']
                args += ['-D' + d for d in defines]
                subprocess.run(args + [str(directory/'Shaders'/source), '-Fo', str(binary)], check=True)
                widen(binary)
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.2', str(binary)], check=True)
            if not validate:
                data = binary.read_bytes(); words = struct.unpack('<' + 'I' * (len(data)//4), data)
                output += f'inline constexpr uint32_t shader{i}[] = {{\n'
                for j in range(0, len(words), 8):
                    output += '  ' + ', '.join(f'0x{x:08x}' for x in words[j:j+8]) + ',\n'
                output += '};\n'
        output += 'struct Shader { const char *identifier; const uint32_t *code; size_t size; };\ninline constexpr Shader shaders[] = {\n'
        for i, identifier in enumerate(IDENTIFIERS):
            output += f'  {{"{identifier}", shader{i}, sizeof(shader{i})}},\n'
        output += '};\n}\n'
    if validate: return
    if check:
        if target.read_text() != output: raise SystemExit('NRD embedded shaders differ')
    else: target.write_text(output)
